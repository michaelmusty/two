function QuadricsModuloCurve(J,IC,mon)
 R:=Generic(IC); candidates:=[];
 for f in GroebnerBasis(J) do
  d:=TotalDegree(f);
  if d gt 2 then continue;end if;
  if d eq 2 then Append(~candidates,NormalForm(f,IC));
  elif d eq 1 then candidates cat:=[NormalForm(f*R.i,IC):i in [1..Rank(R)]];
  else error "unexpected degree-zero divisor ideal";
  end if;
 end for;
 A:=Matrix(BaseRing(R),#candidates,#mon,&cat[[MonomialCoefficient(f,m):m in mon]:f in candidates]);
 return [&+[v[j]*mon[j]:j in [1..#mon]]:v in Basis(RowSpace(A))];
end function;
function ReduceEffective(J,IC,P,pt,pointideals,mon)
 R:=Generic(IC); d:=Degree(Scheme(P,J));
 if d le 16 then return J;end if;
 assert d le 32;
 qs:=QuadricsModuloCurve(J,IC,mon);
 ok:=false;q:=R!0;
 for candidate in qs do if Evaluate(candidate,pt) ne 0 then ok:=true;q:=candidate;break;end if;end for;
 assert ok;
 E:=Saturation(ColonIdeal(IC+ideal<R|q>,J));
 assert Degree(Scheme(P,E)) eq 60-d;
 m:=d-16; required:=E meet pointideals[m];
 assert Degree(Scheme(P,required)) eq 60-d+m;
 nums:=QuadricsModuloCurve(required,IC,mon);
 assert #nums gt 0;
 num:=nums[1];
 out:=Saturation(ColonIdeal(IC+ideal<R|num>,required));
 assert Degree(Scheme(P,out)) eq 16;
 removed:=0;
 while Dimension(out+pointideals[1]) gt 0 do
  out:=Saturation(ColonIdeal(out,pointideals[1]));removed+:=1;
  assert removed le 16;
 end while;
 assert Degree(Scheme(P,out)) eq 16-removed;
 return out;
end function;
function DoubleEffective(J,IC,P,mon)
