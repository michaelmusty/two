printf "CHECKPOINT_F_COEFFICIENTS|%o\n",BaseCoefficients(fcoeff)[1];
printf "CHECKPOINT_NORM_SCALAR|%o\n",Integers()!c[1][1,1];
printf "CPU_SECONDS|%o\n",Cputime(started);
