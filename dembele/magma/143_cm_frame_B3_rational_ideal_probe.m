// D75: replace the auxiliary 7*P32 by B3, preserving the square class at 31.
SetQuitOnError(true); SetColumns(0); SetSeed(75);
started:=Cputime(); k:=GF(31);
load "dembele/data/computed/cm_frame_curve_candidate.m";
load "dembele/data/computed/cm_frame_marks.m";
load "dembele/data/computed/cm_frame_resolvent.m";
load "dembele/data/computed/cm_frame_B3_numerator.m";
IC:=Ideal(C_candidate); GC:=GroebnerBasis(IC);
mon:=[R.(p[1])*R.(p[2]):p in pairs];
function Quadric(row,mon)
    return &+[row[j]*mon[j]:j in [1..#mon]];
end function;
function Quadrics(J,IC,mon)
    R:=Generic(IC); candidates:=[];
    for f in GroebnerBasis(J) do
        degree:=TotalDegree(f);
        if degree eq 2 then Append(~candidates,NormalForm(f,IC));
        elif degree eq 1 then candidates cat:=[NormalForm(f*R.i,IC):i in [1..Rank(R)]];
        else assert degree gt 2;
        end if;
    end for;
    A:=Matrix(BaseRing(R),#candidates,#mon,&cat[[MonomialCoefficient(f,m):m in mon]:f in candidates]);
    return [Quadric(Eltseq(v),mon):v in Basis(RowSpace(A))];
end function;
function Choice(qs,i)
    if i le #qs then return qs[i]; end if;
    return &+[Random(BaseRing(Parent(q)))*q:q in qs];
end function;
function CoefficientRow(q,mon)
    return [Integers()!MonomialCoefficient(q,m):m in mon];
end function;
pt:=Eltseq(P32_candidate);
IP:=ideal<R|[R.i-pt[i]/pt[1]*R.1:i in [2..16]]>;
IB2:=D17_ideal meet IP;
IB3twice:=Saturation(IC+ideal<R|[a*b:a,b in B3_linear_forms]>);
IA:=IB2 meet IB3twice;
assert Degree(Scheme(P,IA)) eq 36;
assert #Quadrics(IA,IC,mon) eq 9;
Eqs:=[Quadric(row,mon):row in resolvent_E_quadrics];
IE:=Saturation(IC+ideal<R|Eqs>);
assert Degree(Scheme(P,IE)) eq 16;
assert Dimension(IE+B3_ideal) eq 0;
IEB3:=IE meet B3_ideal;
assert Degree(Scheme(P,IEB3)) eq 25;
gs:=Quadrics(IEB3,IC,mon);
assert #gs eq 20;
found:=false;
for i in [1..#gs+32] do
    g:=Choice(gs,i);
    if Evaluate(g,pt) eq 0 then continue; end if;
    IG:=Saturation(ColonIdeal(IC+ideal<R|g>,IEB3));
    if Degree(Scheme(P,IG)) ne 35 or not IsReduced(Scheme(P,IG)) then continue; end if;
    if Dimension(IG+IEB3) gt 0 or Dimension(IG+IP) gt 0 then continue; end if;
    found:=true; break;
end for;
assert found;
assert Saturation(IC+ideal<R|g>) eq (IEB3 meet IG);
PS<t>:=PowerSeriesRing(k,8);
xs:=[(&+[PS!resolvent_point_jets[n+1][j]*t^n:n in [0..7]])+O(t^8):j in [1..16]];
assert &and[Evaluate(f,xs) eq 0:f in polys];
jetmat:=Matrix(k,[[Coefficient(Evaluate(q,xs),n):q in mon]:n in [0..6]]);
IP7:=Saturation(ideal<R|[Quadric(Eltseq(v),mon):v in Basis(Nullspace(Transpose(jetmat)))]>);
assert Degree(Scheme(P,IP7)) eq 7;
required:=IG meet IP7;
assert Degree(Scheme(P,required)) eq 42;
qs:=Quadrics(required,IC,mon);
assert #qs eq 3;
found:=false;
for i in [1..#qs+32] do
    q:=Choice(qs,i);
    if Coefficient(Evaluate(q,xs),7) eq 0 then continue; end if;
    InewE:=Saturation(ColonIdeal(IC+ideal<R|q>,required));
    if Degree(Scheme(P,InewE)) ne 18 or not IsReduced(Scheme(P,InewE)) then continue; end if;
    if Dimension(InewE+IA) gt 0 or Dimension(InewE+IG) gt 0 or Dimension(InewE+IE) gt 0 then continue; end if;
    found:=true; break;
end for;
assert found;
assert Saturation(IC+ideal<R|q>) eq (required meet InewE);
assert Dimension(IG+IP) eq 0 and Dimension(InewE+IP) eq 0;
newEqs:=Quadrics(InewE,IC,mon);
InewE2:=Saturation(IC+ideal<R|[a*b:a,b in newEqs]>);
assert Degree(Scheme(P,InewE2)) eq 36;
found:=false; selected:=0;
for candidate_index in [1..#B3_numerator_candidates] do
    n:=Quadric(B3_numerator_candidates[candidate_index],mon);
    assert n in IA and not n in IC;
    IT:=Saturation(ColonIdeal(IC+ideal<R|n>,IA));
    if Degree(Scheme(P,IT)) ne 24 or not IsReduced(Scheme(P,IT)) then continue; end if;
    if Dimension(IT+IA) gt 0 or Dimension(IT+InewE2) gt 0 then continue; end if;
    found:=true; selected:=candidate_index; break;
end for;
assert found;
assert Saturation(IC+ideal<R|n>) eq (IA meet IT);
requiredDen:=IT meet InewE2;
assert Degree(Scheme(P,requiredDen)) eq 60;
dens:=Quadrics(requiredDen,IC,mon);
assert #dens eq 1;
d:=dens[1];
assert Saturation(IC+ideal<R|d>) eq requiredDen;
oldn:=Quadric(resolvent_numerator,mon); oldd:=Quadric(resolvent_denominator,mon);
left:=NormalForm(NormalForm(NormalForm(oldn*g,IC)*g,IC)*d,IC);
right:=NormalForm(NormalForm(NormalForm(n*oldd,IC)*q,IC)*q,IC);
assert left ne 0 and right ne 0;
term:=LeadingMonomial(left);
scale:=MonomialCoefficient(right,term)/MonomialCoefficient(left,term);
d*:=scale;
assert scale ne 0;
assert NormalForm(NormalForm(NormalForm(oldn*g,IC)*g,IC)*d,IC) eq right;
print "PASS|B3_SQUARE_CLASS_TRANSFER_MOD31";
printf "SELECTED_CANDIDATE|%o\n",selected;
printf "NEW_NUMERATOR|%o\n",B3_numerator_candidates[selected];
printf "NEW_DENOMINATOR_MOD31|%o\n",CoefficientRow(d,mon);
printf "SQUARE_FACTOR_NUMERATOR_MOD31|%o\n",CoefficientRow(g,mon);
printf "SQUARE_FACTOR_DENOMINATOR_MOD31|%o\n",CoefficientRow(q,mon);
printf "NEW_E_QUADRICS_MOD31|%o\n",[CoefficientRow(a,mon):a in newEqs];
printf "DIVISOR_DEGREES|%o\n",[18,9,18,24];
print "MOVING_SECTION_SPACE_DIMENSION|3";
print "DIVISOR_IDENTITY|D17+P32+2*B3-2*E_new";

