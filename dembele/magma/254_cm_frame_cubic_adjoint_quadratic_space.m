// D82: exact Q-space H0(2*K_C-D17-3*P32), dimension 25.
SetQuitOnError(true); SetColumns(0); started:=Cputime();
k:=Rationals();
load "dembele/data/computed/cm_frame_curve_candidate.m";
load "dembele/data/computed/cm_frame_marks.m";
load "dembele/data/computed/cm_frame_B3_rational_model.m";
load "dembele/data/computed/cm_frame_cover_sections.m";
mon:=[R.(p[1])*R.(p[2]):p in pairs];
num:=&+[rational_numerator[i]*mon[i]:i in [1..136]];
den:=&+[rational_denominator[i]*mon[i]:i in [1..136]];
pt:=[k!z:z in P32_coordinates]; pt:=[z/pt[16]:z in pt];
equations:=polys cat [num];
J:=Matrix(k,[[Evaluate(Derivative(f,j),pt):j in [1..15]]:f in equations]);
E:=EchelonForm(Transpose(J));
selected:=[Min([j:j in [1..92]|E[i,j] ne 0]):i in [1..15]];
assert Rank(J) eq 15; inv:=Transpose(Submatrix(J,selected,[1..15]))^-1;
PS<s>:=PowerSeriesRing(k,4); xs:=[PS!z+O(s^4):z in pt];
for degree in [1..3] do
    rhs:=Vector(k,[-Coefficient(Evaluate(equations[i],xs)-(i eq 92 select s*Evaluate(den,xs) else PS!0),degree):i in selected]);
    corr:=rhs*inv;
    for j in [1..15] do xs[j]+:=corr[j]*s^degree; end for;
end for;
assert &and[Evaluate(f,xs) eq 0:f in polys] and Evaluate(num,xs) eq s*Evaluate(den,xs);
qjets:=[&*[xs[j]^e[j]:j in [1..16]]:e in sections_even_monomial_exponents];
fulljets:=[xs[p[1]]*xs[p[2]]:p in pairs];
djets:=[&+[row[j]*fulljets[j]:j in [1..136]]:row in D17_extra_rows];
conditions:=Matrix(k,[[Coefficient(f,j):j in [0..2]]:f in djets]);
assert Rank(conditions) eq 3;
K:=Matrix(Basis(Nullspace(conditions))); assert Nrows(K) eq 25;
formal:=K*Matrix(k,D17_extra_rows);
qindices:=[Index([Exponents(m):m in mon],e):e in sections_even_monomial_exponents];
assert #Seqset(qindices) eq 45 and not 0 in qindices;
chart:=Submatrix(IdentityMatrix(k,136),qindices,[1..136]);
frame:=VerticalJoin(Matrix(k,rows),chart); assert Rank(frame) eq 136;
coordinates:=Solution(frame,formal);
basis:=Submatrix(coordinates,[1..25],[92..136]);
assert formal-basis*chart eq Submatrix(coordinates,[1..25],[1..91])*Matrix(k,rows);
assert Rank(basis) eq 25;
jmat:=Matrix(k,[[Coefficient(f,j):j in [0..3]]:f in qjets]);
assert basis*Submatrix(jmat,[1..45],[1..3]) eq 0;
ints:=[];
for row in Rows(basis) do
    ds:=LCM([Denominator(x):x in Eltseq(row)]);
    z:=[Integers()!(ds*x):x in Eltseq(row)]; content:=GCD(z);
    Append(~ints,[x div content:x in z]);
end for;
printf "ADJOINT_QUADRATIC_SPACE_INTEGER_ROWS|%o\n",ints;
printf "ADJOINT_QUADRATIC_SPACE_LEADING_WEIGHTS|%o\n",[[Numerator(jmat[i,4]),Denominator(jmat[i,4])]:i in [1..45]];
printf "CPU_SECONDS|%o\n",Cputime(started);
print "PASS|254_CM_FRAME_CUBIC_ADJOINT_QUADRATIC_SPACE";quit;
