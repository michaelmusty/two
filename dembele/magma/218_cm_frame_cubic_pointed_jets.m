// D82: exact jets at the rational transposition point, with local parameter w.
SetQuitOnError(true); SetColumns(0); started:=Cputime();
k:=GF(31);
load "dembele/data/computed/cm_frame_curve_candidate.m";
load "dembele/data/computed/cm_frame_marks.m";
load "dembele/data/computed/cm_frame_B3_rational_model.m";
load "dembele/data/computed/cm_frame_B3_fiber_structure.m";
load "dembele/data/computed/cm_frame_cover_sections.m";
load "dembele/data/computed/cm_frame_cover_makdisi.m";
load "dembele/data/computed/cm_frame_cubic.m";
Z:=Integers(31^precision_digits); PZ:=PolynomialRing(Z,16);
mon:=[PZ.(p[1])*PZ.(p[2]):p in pairs];
curve:=[&+[row[i]*mon[i]:i in [1..136]]:row in rows];
num:=&+[rational_numerator[i]*mon[i]:i in [1..136]];
den:=&+[rational_denominator[i]*mon[i]:i in [1..136]];
ell:=&+[branch_parameter_linear_form[i]*PZ.i:i in [1..16]];
pt:=[Z!z:z in P32_coordinates]; pt:=[z*pt[16]^-1:z in pt];
assert &and[Evaluate(f,pt) eq 0:f in curve];
assert Evaluate(num,pt) eq 0 and IsUnit(Evaluate(den,pt)*Evaluate(ell,pt));
equations:=curve cat [num];
J:=Matrix(Z,[[Evaluate(Derivative(f,j),pt):j in [1..15]]:f in equations]);
E:=EchelonForm(Transpose(ChangeRing(J,GF(31))));
selected:=[Min([j:j in [1..92]|E[i,j] ne 0]):i in [1..15]];
assert Rank(ChangeRing(J,GF(31))) eq 15;
inv:=Transpose(Submatrix(J,selected,[1..15]))^-1;
PS<t>:=PowerSeriesRing(Z,244); xs:=[PS!z+O(t^244):z in pt];
for d in [1..121] do
    degree:=2*d;
    rhs:=Vector(Z,[-Coefficient(Evaluate(equations[i],xs)-(i eq 92 select t^2*Evaluate(den,xs) else PS!0),degree):i in selected]);
    corr:=rhs*inv;
    for j in [1..15] do xs[j]+:=corr[j]*t^degree; end for;
end for;
assert &and[Evaluate(f,xs) eq 0:f in curve];
assert Evaluate(num,xs) eq t^2*Evaluate(den,xs);
function Mon(e,xs) return &*[xs[j]^e[j]:j in [1..16]]; end function;
even:=[Mon(e,xs):e in sections_even_monomial_exponents];
mons3:=[Mon(e,xs):e in sections_odd_monomial_exponents];
odd:=[&+[cubic_lift_odd_section_rows[i][j]*mons3[j]:j in [1..75]]:i in [1..36]];
jets1:=even cat [t*o*Evaluate(ell,xs)^-1:o in odd];
jets2:=[jets1[p[1]]*jets1[p[2]]:p in makdisi_product2_pairs];
fb:=Setseq({e[1..14]:e in cubic_decic_monomials}); Sort(~fb); assert #fb eq 30;
septic:=&cat[[e cat [j,7-&+e-j]:j in [0..7-&+e]]:e in fb]; assert #septic eq 195;
aweights:=[Coefficient(Mon(e,xs),160):e in cubic_quartic_monomials];
bweights:=[Coefficient(Mon(e,xs)*Evaluate(ell,xs)^-1,240):e in septic];
printf "POINTED_JET1_COEFFICIENTS|%o\n",[[Integers()!Coefficient(f,j):j in [0..79]]:f in jets1];
printf "POINTED_JET2_COEFFICIENTS|%o\n",[[Integers()!Coefficient(f,j):j in [0..79]]:f in jets2];
printf "POINTED_CURVE_JETS|%o\n",[[Integers()!Coefficient(f,j):j in [0..243]]:f in xs];
printf "POINTED_JACOBIAN_ROWS|%o\n",selected;
printf "POINTED_SEPTIC_MONOMIALS|%o\n",septic;
printf "POINTED_A_LEADING_WEIGHTS|%o\n",[Integers()!x:x in aweights];
printf "POINTED_TRACE_LEADING_WEIGHTS|%o\n",[Integers()!x:x in bweights];
printf "CPU_SECONDS|%o\n",Cputime(started);
print "PASS|218_CM_FRAME_CUBIC_POINTED_JETS";quit;
