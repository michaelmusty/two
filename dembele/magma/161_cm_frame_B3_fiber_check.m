// D77 independent normalized-fibre certificate: no solves or square-root search.
SetQuitOnError(true); SetColumns(0); SetSeed(77);
started:=Cputime();
load "dembele/data/computed/cm_frame_B3_fiber.m";
load "dembele/data/computed/cm_frame_B3_fiber_structure.m";
load "dembele/data/computed/cm_frame_B3_rational_model.m";
k:=Rationals();
load "dembele/data/computed/cm_frame_curve_candidate.m";
load "dembele/data/computed/cm_frame_marks.m";
U<z>:=PolynomialRing(k); f:=U!fiber_nonic_coefficients;
assert Degree(f) eq 9 and IsIrreducible(f);
K<a>:=NumberField(f);
pt:=[K!row:row in fiber_point_coordinates];
v:=[K!row:row in fiber_tangent];
v2:=[K!row:row in fiber_second_jet];
assert pt[15] eq a and pt[16] eq 1;
assert v[15] eq 1 and v[16] eq 0 and v2[15] eq 0 and v2[16] eq 0;
assert &and[Evaluate(q,pt) eq 0:q in polys cat B3_linear_forms];
J:=Matrix(K,[[Evaluate(Derivative(polys[i],j),pt):j in [1..14]]:i in fiber_jacobian_rows_one_based]);
assert Determinant(J) ne 0;
PS<t>:=PowerSeriesRing(K,3);
xs:=[pt[i]+v[i]*t+v2[i]*t^2+O(t^3):i in [1..16]];
assert &and[Evaluate(q,xs) eq 0:q in polys];
mon:=[R.(p[1])*R.(p[2]):p in pairs];
n:=&+[rational_numerator[i]*mon[i]:i in [1..#mon]];
d:=&+[rational_denominator[i]*mon[i]:i in [1..#mon]];
nj:=Evaluate(n,xs); dj:=Evaluate(d,xs);
assert Coefficient(nj,0) eq 0 and Coefficient(nj,1) eq 0;
n2:=K!fiber_numerator_leading; d0:=K!fiber_denominator_value;
alpha:=K!fiber_unit;
assert Coefficient(nj,2) eq n2 and Coefficient(dj,0) eq d0;
assert n2 ne 0 and d0 ne 0;
assert n2 eq d0*alpha;
assert Norm(alpha) eq fiber_unit_norm and fiber_unit_norm lt 0;
print "PASS|NORMALIZED_FIBER_FROM_ALL_EXACT_JETS";

s:=K!branch_squareclass_witness;
assert branch_squareclass eq -3 and s ne 0 and alpha eq -3*s^2;
ell:=&+[branch_parameter_linear_form[i]*R.i:i in [1..16]];
assert ell eq B3_linear_forms[branch_parameter_linear_form_index_one_based];
assert Evaluate(ell,pt) eq 0;
slope:=K!branch_parameter_slope; curvature:=K!branch_parameter_second_coefficient;
assert Coefficient(Evaluate(ell,xs),1) eq slope and Coefficient(Evaluate(ell,xs),2) eq curvature;
assert slope ne 0;
ratio:=K!branch_branch_ratio; beta:=K!branch_rational_parameter_unit;
assert ratio*slope eq s and beta*slope^2 eq alpha;
assert beta eq -3*ratio^2;
vnew:=[K!row:row in branch_changed_tangent];
wnew:=[K!row:row in branch_changed_second_jet];
newxs:=[pt[i]+vnew[i]*t+wnew[i]*t^2+O(t^3):i in [1..16]];
assert Evaluate(ell,newxs) eq t;
assert &and[Evaluate(q,newxs) eq 0:q in polys];
newnj:=Evaluate(n,newxs);
assert Coefficient(newnj,0) eq 0 and Coefficient(newnj,1) eq 0;
assert Coefficient(newnj,2) eq d0*beta;

// The norm of -3 is negative since [K:Q]=9, so b^2+3 is irreducible.
assert Norm(K!-3) eq (-3)^9;
V<b>:=PolynomialRing(K); H<h>:=quo<V|b^2+3>;
zz:=s*h; ww:=ratio*h; zeta:=(-1+h)/2;
assert zz^2 eq H!alpha and ww^2 eq H!beta;
assert zeta^2+zeta+1 eq 0 and zeta ne 1;
inv:=hom<H->H|-h>;
assert inv(inv(h)) eq h and inv(zz) eq -zz and inv(ww) eq -ww;
assert inv(zeta) eq zeta^2;
Q<c>:=PolynomialRing(H); A<y>:=quo<Q|c^2-beta>;
eplus:=(1+y/(ratio*h))/2; eminus:=(1-y/(ratio*h))/2;
assert eplus^2 eq eplus and eminus^2 eq eminus;
assert eplus*eminus eq 0 and eplus+eminus eq 1;
swap:=hom<A->A|-y>;
assert swap(eplus) eq eminus and swap(eminus) eq eplus;
print "PASS|CYCLOTOMIC_FIBER_AND_ORIENTED_BRANCHES";

// Retain a good special fibre for future degree-three divisor arithmetic.
k31:=GF(31); T31<x>:=PolynomialRing(k31);
f31:=T31!fiber_nonic_coefficients;
assert Degree(f31) eq 9 and Degree(GCD(f31,Derivative(f31))) eq 0;
A31<a31>:=quo<T31|f31>;
alpha31:=A31!T31!fiber_unit; s31:=A31!T31!branch_squareclass_witness;
beta31:=A31!T31!branch_rational_parameter_unit; ratio31:=A31!T31!branch_branch_ratio;
assert alpha31 eq -3*s31^2 and beta31 eq -3*ratio31^2;
assert IsUnit(alpha31) and IsUnit(beta31) and IsUnit(ratio31);
b31:=k31!11; assert b31^2 eq -3;
plus:=b31*ratio31; minus:=-plus;
assert plus^2 eq beta31 and minus^2 eq beta31 and IsUnit(plus-minus);
printf "B3_FACTOR_DEGREES_MOD31|%o\n",[Degree(t[1]):t in Factorization(f31)];
printf "BRANCH_PLUS_VALUES_MOD31|%o\n",[Integers()!Coefficient(T31!plus,i):i in [0..8]];
printf "BRANCH_MINUS_VALUES_MOD31|%o\n",[Integers()!Coefficient(T31!minus,i):i in [0..8]];
print "FIBER_FIELD_DEGREE|18";
print "ORIENTED_BRANCH_DEGREES|[9,9]";
printf "CPU_SECONDS|%o\n",Cputime(started);
print "PASS|161_CM_FRAME_B3_FIBER_CHECK";
quit;
