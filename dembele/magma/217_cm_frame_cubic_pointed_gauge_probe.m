// D82: test a field-preserving normalization E=80*P32+E40 in the same class.
// This is a bounded special-fibre feasibility calculation, not a new lift.
SetQuitOnError(true); SetColumns(0); SetSeed(82217); started:=Cputime();
load "dembele/magma/170_cm_frame_cover_class_arithmetic.m";
load "dembele/data/computed/cm_frame_cover_sections.m";
load "dembele/data/computed/cm_frame_cubic.m";
K:=k; k:=GF(31);
load "dembele/data/computed/cm_frame_curve_candidate.m";
load "dembele/data/computed/cm_frame_marks.m";
load "dembele/data/computed/cm_frame_B3_rational_model.m";
load "dembele/data/computed/cm_frame_B3_fiber_structure.m";
mon:=[R.(p[1])*R.(p[2]):p in pairs];
num:=&+[rational_numerator[i]*mon[i]:i in [1..136]];
den:=&+[rational_denominator[i]*mon[i]:i in [1..136]];
ell:=&+[branch_parameter_linear_form[i]*R.i:i in [1..16]];
pt:=[k!z:z in P32_coordinates];
pt:=[z/pt[16]:z in pt];
assert Evaluate(num,pt) eq 0 and Evaluate(den,pt)*Evaluate(ell,pt) ne 0;
equations:=polys cat [num];
J:=Matrix(k,[[Evaluate(Derivative(f,j),pt):j in [1..15]]:f in equations]);
E:=EchelonForm(Transpose(J));
selected:=[Min([j:j in [1..92]|E[i,j] ne 0]):i in [1..15]];
assert Rank(J) eq 15;
inv:=Transpose(Submatrix(J,selected,[1..15]))^-1;
PS<t>:=PowerSeriesRing(k,82); xs:=[PS!z+O(t^82):z in pt];
for d in [1..40] do
    j:=2*d;
    rhs:=Vector(k,[-Coefficient(Evaluate(equations[i],xs)-(i eq 92 select t^2*Evaluate(den,xs) else PS!0),j):i in selected]);
    corr:=rhs*inv;
    for v in [1..15] do xs[v]+:=corr[v]*t^j; end for;
end for;
assert &and[Evaluate(f,xs) eq 0:f in polys];
assert Evaluate(num,xs) eq t^2*Evaluate(den,xs);
function Mon(e,xs) return &*[xs[j]^e[j]:j in [1..16]]; end function;
even:=[Mon(e,xs):e in sections_even_monomial_exponents];
oddmons:=[Mon(e,xs):e in sections_odd_monomial_exponents];
odd:=[&+[sections_odd_section_rows[i][j]*oddmons[j]:j in [1..75]]:i in [1..36]];
jets1:=even cat [t*o/Evaluate(ell,xs):o in odd];
jets2:=[jets1[p[1]]*jets1[p[2]]:p in makdisi_product2_pairs];
J2:=Matrix(k,[[Coefficient(f,j):j in [0..79]]:f in jets2]);
WRcoords:=Matrix(K,kummer_descended_divisor_coordinates); WR:=WRcoords*V2;
Wjets:=ChangeRing(WRcoords,k)*J2;
mult:=Min([j:j in [1..80]|&or[Wjets[i,j] ne 0:i in [1..81]]])-1;
found:=false;
for trial in [1..128] do
    cs:=Vector(K,[K!Random(k):i in [1..81]]); g:=cs*WR;
    if (ChangeRing(Matrix(K,1,81,Eltseq(cs)),k)*Wjets)[1,mult+1] ne 0 then found:=true; break; end if;
end for;
assert found;
N:=QuotientSpace(WR,ScaleRows(V2,g),V2,81);
Ncoords:=Matrix(Basis(RowSpace(Solution(V2,N))));
assert &and[z^31 eq z:z in Eltseq(Ncoords)];
constraints:=ChangeRing(Ncoords,k)*J2; rank:=Rank(constraints);
printf "POINTED_JET_RANK|%o\n",rank;
printf "POINTED_OLD_MULTIPLICITY|%o\n",mult;
assert rank eq 80;
line:=Matrix(Basis(Nullspace(constraints))); assert Nrows(line) eq 1;
rcoeff:=ChangeRing(line,K)*Ncoords; r:=rcoeff*V2;
newW:=QuotientSpace(N,ScaleRows(V2,r[1]),V2,81);
newC:=Matrix(Basis(RowSpace(Solution(V2,newW))));
assert &and[z^31 eq z:z in Eltseq(newC)];
assert ChangeRing(newC,k)*J2 eq 0;
assert EqualClass(newW,WR);
printf "POINTED_DIVISOR_COORDINATES_MOD31|%o\n",[[Integers()!(k!z):z in Eltseq(row)]:row in Rows(newC)];
printf "POINTED_JACOBIAN_ROWS|%o\n",selected;
printf "POINTED_SECTION_JETS_MOD31|%o\n",[[Integers()!z:z in Eltseq(row)]:row in Rows(J2)];
printf "POINTED_Q_VALUE_MOD31|%o\n",Integers()!Coefficient(&+[kummer_q_coefficients[i]*jets1[i]:i in [1..81]],0);
printf "CPU_SECONDS|%o\n",Cputime(started);
print "PASS|217_CM_FRAME_CUBIC_POINTED_GAUGE_PROBE";quit;
