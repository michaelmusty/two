// D77: normalized fibre of the rational double cover above the nonic B3.
// The local parameter is t=X15/X16-a, with a the residue-field generator.
// Only exact polynomial/number-field arithmetic is used; no maximal order.
SetQuitOnError(true); SetColumns(0); SetSeed(77);
started:=Cputime(); k:=Rationals();
load "dembele/data/computed/cm_frame_curve_candidate.m";
load "dembele/data/computed/cm_frame_marks.m";
load "dembele/data/computed/cm_frame_B3_rational_model.m";
IC:=Ideal(C_candidate); GC:=GroebnerBasis(IC);
assert Degree(B3_candidate) eq 9 and Dimension(B3_ideal+ideal<R|R.16>) eq 0;
S:=PolynomialRing(k,15,"grevlex");
ia:=ideal<S|[Evaluate(f,[S.i:i in [1..15]] cat [S!1]):f in Basis(B3_ideal)]>;
L:=PolynomialRing(k,15,"lex"); il:=ideal<L|[L!f:f in GroebnerBasis(ia)]>;
gl:=GroebnerBasis(il); assert #gl eq 15;
U<z>:=PolynomialRing(k);
f:=Evaluate(gl[#gl],[U!0:i in [1..14]] cat [z]);
f/:=LeadingCoefficient(f);
assert Degree(f) eq 9 and IsIrreducible(f);
cs:=[Evaluate(NormalForm(L.i,il),[U!0:j in [1..14]] cat [z]):i in [1..15]];
assert cs[15] eq z;
shape:=ideal<L|[L.i-Evaluate(cs[i],L.15):i in [1..14]] cat [Evaluate(f,L.15)]>;
assert shape eq il;
cs cat:=[U!1];
assert &and[Evaluate(q,cs) mod f eq 0:q in polys cat B3_linear_forms];
printf "FIBER_NONIC_COEFFICIENTS|%o\n",[Sprint(Coefficient(f,i)):i in [0..9]];
printf "FIBER_POINT_COORDINATES|%o\n",[[Sprint(Coefficient(c,i)):i in [0..8]]:c in cs];
printf "SHAPE_CPU_SECONDS|%o\n",Cputime(started);

K<a>:=NumberField(f);
pt:=[Evaluate(c,a):c in cs];
J:=Matrix(K,[[Evaluate(Derivative(q,j),pt):j in [1..14]]:q in polys]);
JT:=Transpose(J); echelon:=EchelonForm(JT); assert Rank(echelon) eq 14;
selected:=[Min([j:j in [1..#polys]|echelon[i,j] ne 0]):i in [1..14]];
small:=Submatrix(J,selected,[1..14]);
assert Determinant(small) ne 0;
rhs:=Vector(K,[-Evaluate(Derivative(polys[i],15),pt):i in selected]);
v:=Eltseq(Solution(Transpose(small),rhs)) cat [K!1,K!0];
assert &and[&+[Evaluate(Derivative(q,j),pt)*v[j]:j in [1..16]] eq 0:q in polys];
rhs2:=Vector(K,[-Evaluate(polys[i],v):i in selected]);
v2:=Eltseq(Solution(Transpose(small),rhs2)) cat [K!0,K!0];
PS<t>:=PowerSeriesRing(K,3);
xs:=[pt[i]+v[i]*t+v2[i]*t^2+O(t^3):i in [1..16]];
assert xs[15] eq a+t and xs[16] eq 1;
assert &and[Evaluate(q,xs) eq 0:q in polys];
mon:=[R.(p[1])*R.(p[2]):p in pairs];
n:=&+[rational_numerator[i]*mon[i]:i in [1..#mon]];
d:=&+[rational_denominator[i]*mon[i]:i in [1..#mon]];
nj:=Evaluate(n,xs); dj:=Evaluate(d,xs);
assert Coefficient(nj,0) eq 0 and Coefficient(nj,1) eq 0;
n2:=Coefficient(nj,2); d0:=Coefficient(dj,0);
assert n2 ne 0 and d0 ne 0;
alpha:=n2/d0;
printf "FIBER_JACOBIAN_ROWS|%o\n",selected;
printf "FIBER_TANGENT|%o\n",[[Sprint(Coefficient(U!Eltseq(c),i)):i in [0..8]]:c in v];
printf "FIBER_SECOND_JET|%o\n",[[Sprint(Coefficient(U!Eltseq(c),i)):i in [0..8]]:c in v2];
printf "FIBER_NUMERATOR_LEADING|%o\n",[Sprint(Coefficient(U!Eltseq(n2),i)):i in [0..8]];
printf "FIBER_DENOMINATOR_VALUE|%o\n",[Sprint(Coefficient(U!Eltseq(d0),i)):i in [0..8]];
printf "FIBER_UNIT|%o\n",[Sprint(Coefficient(U!Eltseq(alpha),i)):i in [0..8]];
printf "FIBER_UNIT_NORM|%o\n",Sprint(Norm(alpha));
printf "JET_CPU_SECONDS|%o\n",Cputime(started);
print "PASS|157_CM_FRAME_B3_FIBER";
quit;
