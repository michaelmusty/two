// D75: verify saved B3 normalization, without searching for any section.
SetQuitOnError(true); SetColumns(0); SetSeed(75);
started:=Cputime();
load "dembele/data/computed/cm_frame_B3_transfer.m";
B3_new_denominator := [(-c) mod 31:c in B3_new_denominator];
function Quadric(row,mon)
    return &+[row[j]*mon[j]:j in [1..#mon]];
end function;

// Exact rational membership, with coefficients integral at 31.
k:=Rationals();
load "dembele/data/computed/cm_frame_curve_candidate.m";
load "dembele/data/computed/cm_frame_marks.m";
IC:=Ideal(C_candidate); GC:=GroebnerBasis(IC);
mon:=[R.(p[1])*R.(p[2]):p in pairs];
n:=Quadric(B3_new_numerator,mon);
assert n in D17_ideal and Evaluate(n,P32_coordinates) eq 0 and not n in IC;
double_rows:=[[Integers()!MonomialCoefficient(a*b,m):m in mon]:a,b in B3_linear_forms];
A:=Matrix(Integers(),rows cat double_rows);
echelon, transform:=EchelonForm(ChangeRing(A,GF(31)));
assert Rank(echelon) eq 118 and Rank(ChangeRing(A,Rationals())) eq 118;
lifted:=ChangeRing(RowSubmatrix(transform,1,118),Integers())*A;
pivots:=[Minimum([j:j in [1..136]|echelon[i,j] ne 0]):i in [1..118]];
small:=Matrix(Rationals(),[[lifted[i,j]:j in pivots]:i in [1..118]]);
cs:=Solution(small,Vector(Rationals(),[B3_new_numerator[j]:j in pivots]));
assert &and[Denominator(c) mod 31 ne 0:c in Eltseq(cs)];
assert cs*ChangeRing(lifted,Rationals()) eq Vector(Rationals(),B3_new_numerator);
print "PASS|B3_RATIONAL_NUMERATOR_MEMBERSHIP_INTEGRAL_AT_31";

// Reduced residuals and exact multiplicities at the good prime 31.
k:=GF(31);
load "dembele/data/computed/cm_frame_curve_candidate.m";
load "dembele/data/computed/cm_frame_marks.m";
load "dembele/data/computed/cm_frame_resolvent.m";
IC:=Ideal(C_candidate); GC:=GroebnerBasis(IC);
mon:=[R.(p[1])*R.(p[2]):p in pairs];
pt:=Eltseq(P32_candidate);
IP:=ideal<R|[R.i-pt[i]/pt[1]*R.1:i in [2..16]]>;
IB2:=D17_ideal meet IP;
IB3twice:=Saturation(IC+ideal<R|[a*b:a,b in B3_linear_forms]>);
IA:=IB2 meet IB3twice;
assert Degree(Scheme(P,IA)) eq 36;
n:=Quadric(B3_new_numerator,mon); d:=Quadric(B3_new_denominator,mon);
g:=Quadric(B3_square_numerator,mon); q:=Quadric(B3_square_denominator,mon);
IE:=Saturation(IC+ideal<R|[Quadric(row,mon):row in resolvent_E_quadrics]>);
assert Degree(Scheme(P,IE)) eq 16;
IEB3:=IE meet B3_ideal;
assert Degree(Scheme(P,IEB3)) eq 25 and Dimension(IE+B3_ideal) eq 0;
assert g in IEB3 and Evaluate(g,pt) ne 0;
IG:=Saturation(ColonIdeal(IC+ideal<R|g>,IEB3));
assert Degree(Scheme(P,IG)) eq 35 and IsReduced(Scheme(P,IG));
assert Dimension(IG+IEB3) eq 0 and Dimension(IG+IP) eq 0;
assert Saturation(IC+ideal<R|g>) eq (IEB3 meet IG);
PS<t>:=PowerSeriesRing(k,8);
xs:=[(&+[PS!resolvent_point_jets[n+1][j]*t^n:n in [0..7]])+O(t^8):j in [1..16]];
assert &and[Evaluate(f,xs) eq 0:f in polys];
jets:=Matrix(k,[[Coefficient(Evaluate(a,xs),n):a in mon]:n in [0..6]]);
IP7:=Saturation(ideal<R|[Quadric(Eltseq(v),mon):v in Basis(Nullspace(Transpose(jets)))]>);
assert Degree(Scheme(P,IP7)) eq 7;
assert Coefficient(Evaluate(q,xs),7) ne 0;
newEqs:=[Quadric(row,mon):row in B3_new_E_quadrics];
InewE:=Saturation(IC+ideal<R|newEqs>);
InewE2:=Saturation(IC+ideal<R|[a*b:a,b in newEqs]>);
assert Degree(Scheme(P,InewE)) eq 18 and IsReduced(Scheme(P,InewE));
assert Degree(Scheme(P,InewE2)) eq 36;
assert Dimension(InewE+IA) eq 0 and Dimension(InewE+IG) eq 0 and Dimension(InewE+IE) eq 0;
assert Saturation(IC+ideal<R|q>) eq (InewE meet IG meet IP7);
assert n in IA;
IT:=Saturation(ColonIdeal(IC+ideal<R|n>,IA));
assert Degree(Scheme(P,IT)) eq 24 and IsReduced(Scheme(P,IT));
assert Dimension(IT+IA) eq 0 and Dimension(IT+InewE2) eq 0;
assert Saturation(IC+ideal<R|n>) eq (IA meet IT);
assert Saturation(IC+ideal<R|d>) eq (InewE2 meet IT);
oldn:=Quadric(resolvent_numerator,mon); oldd:=Quadric(resolvent_denominator,mon);
left:=NormalForm(NormalForm(NormalForm(oldn*g,IC)*g,IC)*d,IC);
right:=NormalForm(NormalForm(NormalForm(n*oldd,IC)*q,IC)*q,IC);
assert left ne 0 and right ne 0;
assert left eq right;
print "PASS|B3_EXACT_SQUARE_CHANGE_OF_VARIABLE_MOD31";
print "ODD_BRANCH_DEGREE|18";
print "DOUBLE_COVER_GENUS|40";
printf "CPU_SECONDS|%o\n",Cputime(started);
print "PASS|145_CM_FRAME_B3_CHECK";
quit;
