SetColumns(0); SetSeed(71); SetQuitOnError(true);
k:=GF(31);
load "dembele/data/computed/cm_frame_curve_candidate.m";
load "dembele/data/computed/cm_frame_marks.m";
started:=Cputime(); I:=Ideal(C_candidate); G:=GroebnerBasis(I);
LM:=[LeadingMonomial(f):f in G]; B:=[R!1]; layer:=[R!1];
repeat
 layer:=Setseq({m*R.i:m in layer,i in [1..14] | not &or[IsDivisibleBy(m*R.i,l):l in LM]});
 B cat:= layer;
until #layer eq 0;
Sort(~B); assert #B eq 30;
K<t>:=FunctionField(k); T<y>:=PolynomialRing(K);
function NFVector(f,I,B,K)
 R:=Generic(I); nf:=NormalForm(f,I); out:=[K!0:b in B];
 cs,ms:=CoefficientsAndMonomials(nf);
 for a in [1..#cs] do
  ee:=Exponents(ms[a]); m:=ExactQuotient(ms[a],R.15^ee[15]*R.16^ee[16]);
  j:=Index(B,m); assert j gt 0; out[j]+:=cs[a]*K.1^ee[15];
 end for;
 return Vector(K,out);
end function;
M:=Matrix(K,[Eltseq(NFVector(R.14*b,I,B,K)):b in B]);
f:=CharacteristicPolynomial(M);
print "CHARPOLY",Degree(f),Cputime(started);
F<a>:=FunctionField(f);
print "FIELD_CREATED",Cputime(started);
rows:=[Vector(K,[K!1] cat [K!0:i in [2..30]])];
for j in [2..30] do Append(~rows,rows[#rows]*M);end for;
V:=Matrix(rows); assert Rank(V) eq 30;
print "POWER_BASIS",Cputime(started);
U<s>:=PolynomialRing(k);
VP:=Matrix(U,30,30,[U!c:c in Eltseq(V)]);
WI,wd:=PseudoInverse(VP);
assert VP*WI eq wd*IdentityMatrix(U,30);
W:=Matrix(K,WI)/(K!wd);
print "INVERSE",Degree(wd),Cputime(started);
bas:=[&+[F!W[i,j]*a^(j-1):j in [1..30]]:i in [1..30]];
coords:=[bas[Index(B,R.i)]:i in [1..14]] cat [F!t,F!1];
print "COORDINATES_CREATED",Cputime(started);
O:=Order(EquationOrderFinite(F),bas:IsBasis:=true,Verify:=false);
d:=Discriminant(O);
print "ORDER_DISCRIMINANT_DEGREE",Degree(d),Cputime(started);
assert Degree(d) eq 90 and Degree(GCD(d,Derivative(d))) eq 0;
SetOrderMaximal(O,true);
assert MaximalOrderFinite(F) eq O;
print "FINITE_ORDER_MAXIMAL",Cputime(started);
basinf:=[bas[j]/t^TotalDegree(B[j]):j in [1..30]];
OI:=Order(EquationOrderInfinite(F),basinf:IsBasis:=true,Verify:=false);
di:=Discriminant(OI);
assert Degree(Numerator(K!di)) eq Degree(Denominator(K!di));
SetOrderMaximal(OI,true);
assert MaximalOrderInfinite(F) eq OI;
print "INFINITE_ORDER_MAXIMAL",Cputime(started);
print "GENUS",Genus(F),Cputime(started);
assert Degree(F) eq 30 and Genus(F) eq 16;
assert Dimension(D17_ideal+ideal<R|R.16>) eq 0;
pt:=Eltseq(P32_candidate); assert pt[16] ne 0;
ob:=[O!b:b in bas];
assert &and[Eltseq(ob[j]) eq [K!(i eq j select 1 else 0):i in [1..30]]:j in [1..30]];
print "ORDER_BASIS_COERCED",Cputime(started);
function ToO(q,I,B,K,ob)
 v:=NFVector(q,I,B,K);
 OO:=Parent(ob[1]); return elt<OO|Eltseq(v)>;
end function;
dg:=[ToO(q,I,B,K,ob):q in D17_extra_quadrics];
print "D17_GENERATORS",Cputime(started);
JD:=ideal<O|dg>;
print "D17_IDEAL",Cputime(started);
JP:=ideal<O|[ToO(R.i-pt[i]/pt[16]*R.16,I,B,K,ob):i in [1..15]]>;
print "POINT_IDEAL",Cputime(started);
print "POINT_NORM_DEGREE",Degree(Norm(JP)),Cputime(started);
print "D17_NORM_DEGREE",Degree(Norm(JD)),Cputime(started);
assert IsPrime(JP);
print "POINT_IS_PRIME",Cputime(started);
PP:=Place(JP);
print "POINT_PLACE",Cputime(started);
oneinf:=ideal<OI|1>;
print "ONE_INFINITY",Cputime(started);
DP:=1*PP;
print "POINT_DIVISOR_CREATED",Cputime(started);
assert IsPrime(JD);
DD:=1*Place(JD);
print "D17_DIVISOR_CREATED",Cputime(started);
assert Degree(DP) eq 1 and Degree(DD) eq 17;
print "MARK_DIVISORS",Cputime(started);
D0:=DD-17*DP;
rr,nu:=Reduction(D0,DP); Dred:=rr+nu*DP;
assert Degree(Dred) eq 0;
print "REDUCED_BRANCH",Degree(rr),Cputime(started);
for j in [1..3] do
 stage:=Cputime(); rr,nu:=Reduction(2*Dred,DP); Dred:=rr+nu*DP;
 print "DOUBLE",j,Degree(rr),Cputime(stage),Cputime(started);
end for;
print "PASS|DIVISOR_REDUCTION_PROBE";quit;
