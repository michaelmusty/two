"""Exact minor certificate excluding trigonal curves via specialization.

A graph minor of minimum degree four gives treewidth at least four,
which bounds metric-graph and curve gonality below. Petri then applies.
"""
import json
from pathlib import Path
import random
import networkx as nx

DATA=Path(__file__).resolve().parents[1]/'data/computed'


def main():
    raw=json.loads((DATA/'stable_graph_audit.json').read_text())
    original=nx.Graph()
    original.add_edges_from((u,v) for u,v,_ in raw['edges'])
    graph=original.copy()
    branches={v:{v} for v in graph}
    rng=random.Random(0)
    contractions=[]
    while min(dict(graph.degree()).values())<4:
        degree=min(dict(graph.degree()).values())
        candidates=[v for v in graph if graph.degree(v)==degree]
        v=rng.choice(candidates)
        u=min(graph[v],key=lambda u:(len(set(graph[v])&set(graph[u])),graph.degree(u),rng.random()))
        branches[u]|=branches.pop(v)
        contractions.append([u,v])
        graph=nx.contracted_nodes(graph,u,v,self_loops=False)
        if len(graph)<5:
            raise RuntimeError('search failed to find a sufficient minor')
    # Verify the witness directly from the original graph, independently
    # of contraction metadata or the search heuristic.
    labels=sorted(branches)
    assert set.union(*branches.values())==set(original)
    assert sum(map(len,branches.values()))==len(original)
    assert all(nx.is_connected(original.subgraph(part)) for part in branches.values())
    witness=nx.Graph()
    witness.add_nodes_from(labels)
    for i,u in enumerate(labels):
        for v in labels[i+1:]:
            if any(original.has_edge(a,b) for a in branches[u] for b in branches[v]):
                witness.add_edge(u,v)
    assert {frozenset(e) for e in witness.edges()}=={frozenset(e) for e in graph.edges()}
    assert min(dict(witness.degree()).values())>=4
    report={'status':'PASS: connected disjoint branch sets certify a graph minor of minimum degree four',
            'branch_sets':{v:sorted(branches[v]) for v in labels},
            'minor_edges':list(witness.edges()),'minor_degrees':dict(witness.degree()),
            'contractions':contractions,'treewidth_lower_bound':4,
            'metric_gonality_lower_bound':4,'curve_gonality_lower_bound':4,
            'consequence':'the genus-16 canonical ideal is generated by its 91 quadrics (Petri)',
            'exact_jet_bound_for_quadrics':61}
    text=json.dumps(report,indent=2)
    (DATA/'quadric_generation.json').write_text(text+'\n')
    (DATA/'quadric_generation.out').write_text(text+'\n')
    print(text)


if __name__=='__main__':
    main()
